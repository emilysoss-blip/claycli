# -*- coding: utf-8 -*-
"""
Generate the Python for the workflow's code nodes from the same source the local tests run.

The tiering rules exist once, in tiering.py. This script lifts CRITERIA, _tri and evaluate
out of it verbatim and wraps them in the handler(context) a Clay code node expects, so the
Clay node and build/test_engine.py cannot drift apart. Output: eightfold/clay/nodes/*.py.
"""
import inspect, os, pprint, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tiering

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(BASE, "clay", "nodes")
os.makedirs(OUT, exist_ok=True)

RULES = "\n".join([
    "from datetime import date",
    "",
    "CRITERIA = " + pprint.pformat(tiering.CRITERIA, width=100, sort_dicts=False),
    "",
    inspect.getsource(tiering._tri),
    inspect.getsource(tiering.evaluate),
])

# Shared by the tiering node and the reconcile node. Missing upstream values arrive as None or
# "" and stay unknown; a provider returning nothing is not evidence of absence.
FACTS = '''
def _num(v):
    try:
        return None if v in (None, "") else float(v)
    except (TypeError, ValueError):
        return None


# Product names PredictLeads (or a Claygent) may return that do mean the HCM / ATS itself.
# Matching is exact per comma-separated item: "Workday Financial Management" or
# "Workday Prism Analytics" are Workday products, but not evidence of Workday HCM.
HCM_ALIASES = {
    "Workday": ["workday", "workday hcm", "workday human capital management", "workday recruiting", "workday ats"],
    "SAP SuccessFactors": ["sap successfactors", "successfactors"],
    "Oracle HCM": ["oracle hcm", "oracle human capital management", "oracle human capital management (hcm)", "oracle hcm cloud"],
    "Taleo": ["taleo", "oracle taleo"],
    "iCIMS": ["icims"],
    "Greenhouse": ["greenhouse"],
    "SmartRecruiters": ["smartrecruiters"],
    "Avature": ["avature"],
    "Phenom": ["phenom", "phenom people"],
}


def _hcm_from(text):
    """Supported HCM / ATS names in a comma-separated technology list. Absence stays unknown."""
    if not text:
        return None
    items = {i.strip().lower() for i in str(text).split(",") if i.strip()}
    hits = [name for name, aliases in HCM_ALIASES.items()
            if name in CRITERIA["hcm_supported"] and items & set(aliases)]
    return hits or None


def _facts(context, hcm):
    return {
        "vertical": context.get_input("vertical"),
        "employees": _num(context.get_input("employee_count")),
        "open_reqs": _num(context.get_input("job_count")),
        "hcm": hcm,
        "country": context.get_input("country"),
        "disqualifier": None,
        "identity_unresolved": False,
        "as_of": "",
    }


def _out(r, hcm, open_reqs, source):
    return {
        "fit_score": r["fit_score"],
        "fit_best_case": r["fit_best_case"],
        "fit_tier": r["fit_tier"],
        "missing_required_fields": r["missing_required_fields"] or "none",
        "score_reasons": r["score_reasons"],
        "score_version": r["score_version"],
        "check_hcm": r["check_hcm"],
        "check_open_reqs": r["check_open_reqs"],
        "check_headcount": r["check_headcount"],
        "hcm_detected": ", ".join(hcm) if hcm else "unknown",
        "hcm_source": source,
        "open_reqs": -1 if open_reqs is None else open_reqs,
    }
'''

TIERING = f'''# Generated by eightfold/build/node_code.py from eightfold/build/tiering.py. Do not edit here.
{RULES}
{FACTS}

def handler(context):
    hcm = _hcm_from(context.get_input("technologies_found"))
    facts = _facts(context, hcm)
    r = evaluate(facts)
    return _out(r, hcm, facts["open_reqs"], "PredictLeads technographics" if hcm else "none")
'''

RECONCILE = f'''# Generated by eightfold/build/node_code.py from eightfold/build/tiering.py. Do not edit here.
# Promotes a Claygent HCM finding only when the evidence is a stated deployment and the
# uncertainty is not high; a clue never fills a required field (clay/claygent_fallback.md).
{RULES}
{FACTS}

def handler(context):
    native = _hcm_from(context.get_input("technologies_found"))
    value = (context.get_input("claygent_hcm") or "").strip()
    evidence = (context.get_input("claygent_evidence_type") or "").strip().lower()
    certainty = (context.get_input("claygent_uncertainty") or "").strip().lower()
    promoted = None
    if not native and value and value.lower() != "unknown" and evidence in ("deployed", "stated") and certainty != "high":
        promoted = _hcm_from(value) or None
    hcm = native or promoted
    facts = _facts(context, hcm)
    r = evaluate(facts)
    src = "PredictLeads technographics" if native else ("Claygent (" + evidence + ")" if promoted else "none")
    out = _out(r, hcm, facts["open_reqs"], src)
    out["claygent_promoted"] = bool(promoted)
    return out
'''

IDENTITY = '''# Identity gate input. Domains that resolve to the wrong company, a stale parent, or only
# satellites are unresolved unless the row carries a pinned LinkedIn company URL.
UNSAFE = ("wrong_company", "no_usable_match", "stale_parent", "satellite_only")


def handler(context):
    status = (context.get_input("domain_match_status") or "").strip()
    ident = (context.get_input("enrichment_identifier") or "").strip()
    pinned = ident.startswith("https://www.linkedin.com/company/")
    if not ident:
        ok, why = False, "no identifier"
    elif status in UNSAFE and not pinned:
        ok, why = False, "domain is " + status + " and no LinkedIn URL is pinned"
    else:
        ok, why = True, ("pinned LinkedIn URL" if pinned else "domain (" + (status or "unclassified") + ")")
    return {
        "identity_resolved": ok,
        "identifier_type": "company_linkedin_url" if pinned else "company_domain",
        "identity_reason": why,
    }
'''

HOLD = '''def handler(context):
    return {"status": "Review", "reason": "identity unresolved: " + (context.get_input("identity_reason") or "")}
'''

for name, src in (("tiering_node.py", TIERING), ("reconcile_node.py", RECONCILE),
                  ("identity_node.py", IDENTITY), ("hold_node.py", HOLD)):
    open(os.path.join(OUT, name), "w", encoding="utf-8").write(src)
print("wrote", sorted(os.listdir(OUT)))
